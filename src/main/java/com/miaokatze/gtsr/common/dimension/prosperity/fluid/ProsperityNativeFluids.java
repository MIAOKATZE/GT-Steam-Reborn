package com.miaokatze.gtsr.common.dimension.prosperity.fluid;

import java.util.IdentityHashMap;
import java.util.LinkedHashMap;
import java.util.Map;

import net.minecraftforge.fluids.Fluid;
import net.minecraftforge.fluids.FluidRegistry;

import gregtech.api.enums.FluidState;
import gregtech.api.enums.Materials;
import gregtech.api.fluid.GTFluidFactory;
import gregtech.api.interfaces.fluid.IGTRegisteredFluid;

/** Stable-name official GT fluid registration; facade identity never requires a GT numeric material slot. */
public final class ProsperityNativeFluids {

    private static final Map<String, Fluid> OWNED = new LinkedHashMap<>();
    private static final Map<Materials, Contract> CONTRACTS = new IdentityHashMap<>();

    private ProsperityNativeFluids() {}

    public static Fluid register(Materials material, boolean gas, int temperature) {
        if (temperature <= 0) throw new IllegalArgumentException("Invalid fluid temperature: " + material.mName);
        String name = material.mName;
        // GTFluidFactory otherwise silently reuses a foreign registration and may mutate its temperature.
        if (FluidRegistry.getFluid(name) != null || OWNED.containsKey(name))
            throw new IllegalStateException("Occupied prosperity fluid name: " + name);
        IGTRegisteredFluid registered = GTFluidFactory.builder(name)
            .withDefaultLocalName(material.mDefaultLocalName)
            .withTextureName("autogenerated")
            .withColorRGBA(material.mRGBa)
            .withStateAndTemperature(gas ? FluidState.GAS : FluidState.LIQUID, temperature)
            .buildAndRegister();
        Fluid fluid = registered.asFluid();
        registered.configureMaterials(material)
            .addLocalizedName(material);
        OWNED.put(name, fluid);
        CONTRACTS.put(material, new Contract(fluid, gas, temperature, color(material)));
        verify(material);
        return fluid;
    }

    /** Checks real registry ownership, facade reverse lookup and the GT .277 physical baseline. */
    public static void verify(Materials material) {
        Contract contract = CONTRACTS.get(material);
        if (contract == null) throw new IllegalStateException("Unregistered native fluid: " + material.mName);
        Fluid fluid = contract.fluid;
        if (OWNED.get(material.mName) != fluid || FluidRegistry.getFluid(material.mName) != fluid
            || (contract.gas ? material.mGas : material.mFluid) != fluid
            || Materials.FLUID_MAP.get(fluid) != material
            || fluid.isGaseous() != contract.gas
            || fluid.getTemperature() != contract.temperature
            || fluid.getDensity() != (contract.gas ? -100 : 1000)
            || fluid.getViscosity() != (contract.gas ? 200 : 1000)
            || fluid.getLuminosity() != 0
            || fluid.getColor() != contract.color)
            throw new IllegalStateException("Native prosperity fluid contract failed: " + material.mName);
    }

    private static int color(Materials material) {
        return (material.mRGBa[0] << 16) | (material.mRGBa[1] << 8) | material.mRGBa[2];
    }

    private static final class Contract {

        private final Fluid fluid;
        private final boolean gas;
        private final int temperature, color;

        private Contract(Fluid fluid, boolean gas, int temperature, int color) {
            this.fluid = fluid;
            this.gas = gas;
            this.temperature = temperature;
            this.color = color;
        }
    }
}
